#!/usr/bin/env node
// The React Native package is self-contained only when every artifact its own
// manifests name is inside its tarball. This gate unpacks the tarball a
// consumer receives and reads the packaged manifests — the podspec, the
// generated Gradle file, the generated CMakeLists.txt and package.json —
// rather than the checkout, so it checks exactly what ships.
//
// It requires the podspec's `vendored_frameworks` XCFramework and each slice
// library its Info.plist names, the CMake `IMPORTED_LOCATION` archive for
// every ABI the Gradle file builds, the Gradle- and CMake-referenced sources
// and include directories, and that `package.json`'s `files` allow-list
// covers all of them. A miss names the file and the manifest that named it.
//
// Usage:
//   node scripts/verify-rn-package.mjs <tarball> <expected-version>
//
// Exit code 0 prints the number of manifest-named artifacts found; any
// problem prints one `rn-package-gate: …` line per problem and exits 1, so
// both the release assembly and the release workflow can call it.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";

const [tarball, expectedVersion] = process.argv.slice(2);
if (!tarball || !expectedVersion) {
  console.error(
    "usage: verify-rn-package.mjs <tarball> <expected-version>",
  );
  process.exit(2);
}
if (!fs.existsSync(tarball)) {
  console.error(`rn-package-gate: the tarball was not produced: ${tarball}`);
  process.exit(1);
}

const unpackDirectory = fs.mkdtempSync(
  path.join(os.tmpdir(), "verify-rn-package-"),
);
// The tile-cache runtime path is asserted against the packaged source: the
// package supports the AAR's API 24 floor, where `java.nio.file` is absent.
const ANDROID_TILE_CACHE_RUNTIME_PATH =
  "android/src/main/java/com/angoratek/rusticmaps/MapsSdkNativeRuntime.kt";
const ANDROID_TILE_CACHE_MODULE_PATH =
  "android/src/main/java/com/angoratek/rusticmaps/MapsSdkNativeModule.kt";
const IOS_TILE_CACHE_RUNTIME_PATH = "ios/MapsSdkNativeRuntime.swift";
const IOS_TILE_CACHE_MODULE_PATH = "ios/MapsSdkNativeModule.mm";
// The build fixes every generation re-applies. Their absence means the
// package was generated by a bare ubrn run and would fail the app build.
const CMAKE_LIBANDROID_MARKER = "find_library(ANDROID_LIB android)";
const CMAKE_LIBANDROID_LINK_ENTRY = "${ANDROID_LIB}";
const IOS_CODEGEN_SPEC_INCLUDE =
  "#import <ReactCodegen/RusticMapsSdk/RusticMapsSdk.h>";
// Only the Objective-C headers are public. The pod's C++ headers would
// otherwise enter the public umbrella, which Swift imports in Objective-C
// mode, and the module fails on `<cassert>` before the app can build.
const IOS_PODSPEC_PUBLIC_HEADERS =
  's.public_header_files = "ios/**/*.h"';
// The generator is required to build a consumer, so it must be a runtime
// dependency; the CMake guard fails fast when its output is absent.
const GENERATOR_DEPENDENCY_NAME = "uniffi-bindgen-react-native";
const CMAKE_GENERATED_BINDINGS_GUARD_MARKER =
  "# rustic-maps: generated bindings guard";
const CMAKE_GENERATED_BINDINGS_FATAL_MARKER =
  "the generated UniFFI C++ bindings are missing";
// React Native autolinking registers one package per dependency. The
// package's descriptor must point at the hand-written entry point that
// exposes the TurboModule, the SDK proxy module and the view manager.
const REACT_NATIVE_CONFIG_FILE = "react-native.config.js";
const AUTOLINKED_PACKAGE_CLASS = "MapsSdkMapHost";
const AUTOLINKED_PACKAGE_MODULE_NAMES = [
  "RusticMapsSdkModule",
  "MapsSdkNativeModule",
  "MapsSdkMapViewManager",
];
// Autolinking's Android discovery scan needs a `*Package` class file in the
// dependency's source tree; the generated one must stay shipped.
const GENERATED_PACKAGE_FILE =
  "android/src/main/java/com/angoratek/rusticmaps/RusticMapsSdkPackage.kt";
// `src/index.ts` is generated; the generation step appends the curated
// surface, and `package.json` advertises that entry as the package root.
const CURATED_ROOT_EXPORTS_MARKER = "// rustic-maps: curated root exports";
const CURATED_ROOT_EXPORTS = [
  "export { MapView } from './MapView';",
  "export { MapsSdk, mapsSdk } from './MapsSdk';",
  "export { rustic_maps };",
];
let problems = [];
try {
  try {
    execFileSync("tar", ["-xzf", tarball, "-C", unpackDirectory], {
      stdio: "pipe",
    });
  } catch (error) {
    console.error(`rn-package-gate: the tarball is unreadable: ${tarball}`);
    if (error.stderr) {
      process.stderr.write(error.stderr.toString());
    }
    process.exit(1);
  }

  const packageDirectory = path.join(unpackDirectory, "package");
  if (!fs.existsSync(packageDirectory)) {
    console.error(
      `rn-package-gate: the tarball does not contain a package/ directory: ${tarball}`,
    );
    process.exit(1);
  }

  // Relative path inside package/ -> the manifest that names it.
  const requirements = new Map();

  function addRequirement(relativePath, namedBy) {
    const normalized = path.posix
      .normalize(relativePath)
      .replace(/^\.\//, "")
      .replace(/\/+$/, "");
    if (!requirements.has(normalized)) {
      requirements.set(normalized, namedBy);
    }
  }

  function readPackageFile(relativePath, namedBy) {
    const absolutePath = path.join(packageDirectory, relativePath);
    if (!fs.existsSync(absolutePath)) {
      problems.push(`missing ${relativePath} (named by ${namedBy})`);
      return null;
    }
    return fs.readFileSync(absolutePath, "utf8");
  }

  let packageJson = null;
  try {
    packageJson = JSON.parse(
      fs.readFileSync(path.join(packageDirectory, "package.json"), "utf8"),
    );
  } catch (error) {
    problems.push(`package.json is missing or unreadable: ${error.message}`);
  }
  if (packageJson) {
    if (packageJson.name !== "@angoratek/rustic-maps-sdk") {
      problems.push(
        `package.json names ${packageJson.name}, not @angoratek/rustic-maps-sdk`,
      );
    }
    if (packageJson.version !== expectedVersion) {
      problems.push(
        `package.json declares version ${packageJson.version}, but the artifact set is ${expectedVersion}`,
      );
    }
    if (!Array.isArray(packageJson.files)) {
      problems.push("package.json declares no files allow-list");
    }
    if (!packageJson.dependencies?.[GENERATOR_DEPENDENCY_NAME]) {
      problems.push(
        `package.json does not declare ${GENERATOR_DEPENDENCY_NAME} as a dependency (consumers need it to build)`,
      );
    }
  }

  // React Native autolinking: the shipped descriptor must resolve the one
  // hand-written package, and that package must expose the modules and the
  // view manager. Without it autolinking registers the generated TurboModule
  // package alone, so `MapsSdkNative` and the `<MapView>` manager are absent
  // from the host's registry.
  addRequirement(GENERATED_PACKAGE_FILE, "the autolinking discovery gate");
  const reactNativeConfig = readPackageFile(
    REACT_NATIVE_CONFIG_FILE,
    "the autolinking gate",
  );
  let androidPackageImportPath = null;
  if (reactNativeConfig) {
    addRequirement(REACT_NATIVE_CONFIG_FILE, "the autolinking gate");
    let parsedConfig = null;
    try {
      parsedConfig = createRequire(
        path.join(packageDirectory, REACT_NATIVE_CONFIG_FILE),
      )(path.join(packageDirectory, REACT_NATIVE_CONFIG_FILE));
    } catch (error) {
      problems.push(
        `${REACT_NATIVE_CONFIG_FILE} is not loadable: ${error.message}`,
      );
    }
    const androidPlatform = parsedConfig?.dependency?.platforms?.android;
    androidPackageImportPath = androidPlatform?.packageImportPath ?? null;
    if (!androidPackageImportPath?.includes(AUTOLINKED_PACKAGE_CLASS)) {
      problems.push(
        `${REACT_NATIVE_CONFIG_FILE} does not name ${AUTOLINKED_PACKAGE_CLASS} as the android packageImportPath`,
      );
    }
    if (!androidPlatform?.packageInstance?.includes(AUTOLINKED_PACKAGE_CLASS)) {
      problems.push(
        `${REACT_NATIVE_CONFIG_FILE} does not name ${AUTOLINKED_PACKAGE_CLASS} as the android packageInstance`,
      );
    }
  }
  const packageImportMatch = androidPackageImportPath?.match(
    /import\s+([\w.]+)\.(\w+)\s*;/,
  );
  if (packageImportMatch) {
    const [, packageName, classSimpleName] = packageImportMatch;
    const classPath = `android/src/main/java/${packageName.replace(/\./g, "/")}/${classSimpleName}.kt`;
    const classSource = readPackageFile(
      classPath,
      `${REACT_NATIVE_CONFIG_FILE} packageImportPath`,
    );
    if (classSource) {
      addRequirement(
        classPath,
        `${REACT_NATIVE_CONFIG_FILE} packageImportPath`,
      );
      for (const moduleName of AUTOLINKED_PACKAGE_MODULE_NAMES) {
        if (!classSource.includes(moduleName)) {
          problems.push(
            `${classPath} does not expose ${moduleName} (named by ${REACT_NATIVE_CONFIG_FILE})`,
          );
        }
      }
    }
  }

  // The podspec's vendored_frameworks, expanded to each XCFramework slice
  // binary its Info.plist names.
  const podspec = readPackageFile("RusticMapsSdk.podspec", "the release assembly");
  if (podspec) {
    addRequirement("RusticMapsSdk.podspec", "the release assembly");
    if (!podspec.includes(IOS_PODSPEC_PUBLIC_HEADERS)) {
      problems.push(
        "RusticMapsSdk.podspec is missing the restricted public-header set (only the Objective-C headers under ios/ are public)",
      );
    }
    const vendored = podspec.match(
      /s\.vendored_frameworks\s*=\s*(\[[\s\S]*?\]|"[^"]*")/,
    );
    if (!vendored) {
      problems.push("RusticMapsSdk.podspec declares no vendored_frameworks");
    } else {
      const frameworks = [...vendored[1].matchAll(/"([^"]+)"/g)].map(
        (match) => match[1],
      );
      if (frameworks.length === 0) {
        problems.push("RusticMapsSdk.podspec declares an empty vendored_frameworks");
      }
      for (const framework of frameworks) {
        addRequirement(framework, "RusticMapsSdk.podspec vendored_frameworks");
        if (!framework.endsWith(".xcframework")) {
          continue;
        }
        const plist = readPackageFile(`${framework}/Info.plist`, framework);
        if (!plist) {
          continue;
        }
        let slices = 0;
        for (const dictionary of plist.matchAll(/<dict>([\s\S]*?)<\/dict>/g)) {
          const identifier = dictionary[1].match(
            /<key>LibraryIdentifier<\/key>\s*<string>([^<]+)<\/string>/,
          );
          if (!identifier) {
            continue;
          }
          const binary =
            dictionary[1].match(
              /<key>BinaryPath<\/key>\s*<string>([^<]+)<\/string>/,
            ) ||
            dictionary[1].match(
              /<key>LibraryPath<\/key>\s*<string>([^<]+)<\/string>/,
            );
          if (!binary) {
            problems.push(
              `${framework} slice ${identifier[1]} names no BinaryPath`,
            );
            continue;
          }
          slices += 1;
          addRequirement(
            `${framework}/${identifier[1]}/${binary[1]}`,
            `${framework}/Info.plist`,
          );
        }
        if (slices === 0) {
          problems.push(`${framework} contains no library slices`);
        }
      }
    }
  }

  // The Gradle file's NDK ABI list and the files it references.
  const gradle = readPackageFile("android/build.gradle", "the release assembly");
  let androidAbis = [];
  if (gradle) {
    addRequirement("android/build.gradle", "the release assembly");
    // API 24/25 gate: the tile-cache path uses `java.io.File`, which exists
    // on every supported API level, so the module needs no core-library
    // desugaring. The compile options must stay at the Java level the
    // generated library declares (Java 8); raising it would silently change
    // the runtime requirement the floor is verified against.
    if (
      !/sourceCompatibility\s+JavaVersion\.VERSION_1_8/.test(gradle) ||
      !/targetCompatibility\s+JavaVersion\.VERSION_1_8/.test(gradle)
    ) {
      problems.push(
        "android/build.gradle no longer declares Java 8 compile options (the API 24 floor relies on java.io.File, which needs no desugaring)",
      );
    }
    const ndkBlock = gradle.match(/ndk\s*\{([\s\S]*?)\}/);
    if (ndkBlock) {
      androidAbis = [...ndkBlock[1].matchAll(/"([^"]+)"/g)].map(
        (match) => match[1],
      );
    }
    if (androidAbis.length === 0) {
      problems.push("android/build.gradle declares no ndk abiFilters");
    }
    const gradleReferences = [
      /consumerProguardFiles\s+'([^']+)'/g,
      /manifest\.srcFile\s+"([^"]+)"/g,
      /path\s+"([^"]*CMakeLists\.txt)"/g,
      /jsRootDir\s*=\s*file\("([^"]+)"\)/g,
    ];
    for (const reference of gradleReferences) {
      for (const match of gradle.matchAll(reference)) {
        addRequirement(
          path.posix.join("android", match[1]),
          "android/build.gradle",
        );
      }
    }
  }

  // The tile-cache path must stay API 24/25 safe: `java.nio.file.Paths`
  // exists only from API 26, so a packaged runtime that still references it
  // crashes on the AAR's floor. The path is built with `java.io.File`.
  const tileCacheRuntime = readPackageFile(
    ANDROID_TILE_CACHE_RUNTIME_PATH,
    "the API 24/25 tile-cache gate",
  );
  if (tileCacheRuntime) {
    addRequirement(ANDROID_TILE_CACHE_RUNTIME_PATH, "the API 24/25 tile-cache gate");
    if (tileCacheRuntime.includes("java.nio.file")) {
      problems.push(
        `${ANDROID_TILE_CACHE_RUNTIME_PATH} references java.nio.file, which is unavailable on API 24/25`,
      );
    }
    if (!tileCacheRuntime.includes("import java.io.File")) {
      problems.push(
        `${ANDROID_TILE_CACHE_RUNTIME_PATH} does not import java.io.File for the cache path`,
      );
    }
    // The time-to-live guard must ship in both Android layers: the module
    // converts the bridge number and the runtime checks the provider's
    // terms ceiling before the contract's u64 conversion.
    if (
      !tileCacheRuntime.includes("TILE_CACHE_TIME_TO_LIVE_ABOVE_CEILING_TEMPLATE") ||
      !tileCacheRuntime.includes("rasterTileCacheTerms()")
    ) {
      problems.push(
        `${ANDROID_TILE_CACHE_RUNTIME_PATH} is missing the provider terms-ceiling guard for the tile-cache time-to-live`,
      );
    }
  }
  const tileCacheModule = readPackageFile(
    ANDROID_TILE_CACHE_MODULE_PATH,
    "the time-to-live validation gate",
  );
  if (tileCacheModule) {
    addRequirement(ANDROID_TILE_CACHE_MODULE_PATH, "the time-to-live validation gate");
    for (const marker of [
      "wholeTimeToLiveSeconds",
      "isFinite()",
      "TIME_TO_LIVE_FAILURE_CODE",
    ]) {
      if (!tileCacheModule.includes(marker)) {
        problems.push(
          `${ANDROID_TILE_CACHE_MODULE_PATH} is missing the time-to-live validation marker ${marker}`,
        );
      }
    }
  }
  const iosTimeToLiveRuntime = readPackageFile(
    IOS_TILE_CACHE_RUNTIME_PATH,
    "the time-to-live validation gate",
  );
  if (iosTimeToLiveRuntime) {
    addRequirement(IOS_TILE_CACHE_RUNTIME_PATH, "the time-to-live validation gate");
    for (const marker of [
      "UInt64(exactly:",
      "timeToLiveAboveTermsCeiling",
    ]) {
      if (!iosTimeToLiveRuntime.includes(marker)) {
        problems.push(
          `${IOS_TILE_CACHE_RUNTIME_PATH} is missing the time-to-live validation marker ${marker}`,
        );
      }
    }
  }
  const iosTimeToLiveModule = readPackageFile(
    IOS_TILE_CACHE_MODULE_PATH,
    "the time-to-live validation gate",
  );
  if (iosTimeToLiveModule) {
    addRequirement(IOS_TILE_CACHE_MODULE_PATH, "the time-to-live validation gate");
    if (!iosTimeToLiveModule.includes("MapsSdkIsValidTimeToLive")) {
      problems.push(
        `${IOS_TILE_CACHE_MODULE_PATH} is missing the time-to-live validation guard`,
      );
    }
  }

  // The CMake build: its compiled sources, include directories and the Rust
  // archive it imports per Android ABI.
  const cmakeLists = readPackageFile(
    "android/CMakeLists.txt",
    "the release assembly",
  );
  if (cmakeLists) {
    addRequirement("android/CMakeLists.txt", "the release assembly");
    // The app build links the Rust archive's wgpu GLES symbols through
    // `libandroid.so`; a bare generation omits that link and fails on a
    // clean `.cxx` cache. Both halves of the applied fix must ship.
    if (!cmakeLists.includes(CMAKE_LIBANDROID_MARKER)) {
      problems.push(
        "android/CMakeLists.txt is missing the re-applied libandroid link line (find_library(ANDROID_LIB android))",
      );
    }
    if (!cmakeLists.includes(CMAKE_LIBANDROID_LINK_ENTRY)) {
      problems.push(
        "android/CMakeLists.txt is missing the re-applied ${ANDROID_LIB} link entry",
      );
    }
    // The package builds the generator's C++ output; a consumer that lacks
    // the generated sources must get an actionable configure-time failure,
    // not a missing-header error inside the compile.
    if (!cmakeLists.includes(CMAKE_GENERATED_BINDINGS_GUARD_MARKER)) {
      problems.push(
        "android/CMakeLists.txt is missing the generated-bindings guard",
      );
    }
    if (!cmakeLists.includes(CMAKE_GENERATED_BINDINGS_FATAL_MARKER)) {
      problems.push(
        "android/CMakeLists.txt's generated-bindings guard carries no FATAL_ERROR message",
      );
    }
    const addLibrary = cmakeLists.match(/add_library\(\s*rustic-maps-sdk\b[\s\S]*?\)/);
    if (!addLibrary) {
      problems.push(
        "android/CMakeLists.txt does not define the rustic-maps-sdk library",
      );
    } else {
      for (const token of addLibrary[0].match(/[^\s()]+/g) || []) {
        if (!/\.(?:cpp|cc|c|hpp|h)$/.test(token) || token.includes("${")) {
          continue;
        }
        addRequirement(
          path.posix.join("android", token),
          "android/CMakeLists.txt add_library",
        );
      }
    }
    const includeDirectories = cmakeLists.match(
      /include_directories\(([\s\S]*?)\)/,
    );
    if (includeDirectories) {
      for (const directory of includeDirectories[1].matchAll(
        /\.\.\/[A-Za-z0-9_./-]+/g,
      )) {
        const relative = path.posix.join("android", directory[0]);
        if (!fs.existsSync(path.join(packageDirectory, relative))) {
          problems.push(
            `missing directory ${relative} (named by android/CMakeLists.txt include_directories)`,
          );
        }
      }
    }
    const importedLocations = [
      ...cmakeLists.matchAll(/\$\{CMAKE_SOURCE_DIR\}\/([^)\s]+)/g),
    ].map((match) => match[1]);
    const archiveTemplates = importedLocations.filter(
      (location) =>
        location.includes("jniLibs") && location.includes("${ANDROID_ABI}"),
    );
    if (archiveTemplates.length === 0) {
      problems.push(
        "android/CMakeLists.txt names no per-ABI jniLibs IMPORTED_LOCATION",
      );
    }
    for (const template of archiveTemplates) {
      for (const abi of androidAbis) {
        addRequirement(
          `android/${template.replace("${ANDROID_ABI}", abi)}`,
          "android/CMakeLists.txt IMPORTED_LOCATION",
        );
      }
    }
  }

  // The generated module header must include the ReactCodegen spec umbrella
  // by its public path: a bare generation includes its own header by that
  // basename, so the spec protocol is never declared.
  const iosModuleHeader = readPackageFile(
    "ios/RusticMapsSdk.h",
    "the codegen spec include gate",
  );
  if (iosModuleHeader) {
    addRequirement("ios/RusticMapsSdk.h", "the codegen spec include gate");
    if (!iosModuleHeader.includes(IOS_CODEGEN_SPEC_INCLUDE)) {
      problems.push(
        `ios/RusticMapsSdk.h is missing the re-applied codegen spec include (${IOS_CODEGEN_SPEC_INCLUDE})`,
      );
    }
    if (iosModuleHeader.includes('#import "RusticMapsSdk.h"')) {
      problems.push(
        'ios/RusticMapsSdk.h still self-includes with #import "RusticMapsSdk.h"',
      );
    }
  }

  // The advertised root entry must export the package's curated surface,
  // not only the generated contract: the generation step appends it.
  const rootEntry = readPackageFile(
    "src/index.ts",
    "the curated root entry gate",
  );
  if (rootEntry) {
    addRequirement("src/index.ts", "the curated root entry gate");
    if (!rootEntry.includes(CURATED_ROOT_EXPORTS_MARKER)) {
      problems.push(
        "src/index.ts is missing the appended curated root exports",
      );
    }
    for (const exportLine of CURATED_ROOT_EXPORTS) {
      if (!rootEntry.includes(exportLine)) {
        problems.push(
          `src/index.ts does not export the curated surface: ${exportLine}`,
        );
      }
    }
  }

  // Every named artifact must be present and non-empty.
  for (const [relativePath, namedBy] of requirements) {
    const absolutePath = path.join(packageDirectory, relativePath);
    if (!fs.existsSync(absolutePath)) {
      problems.push(`missing ${relativePath} (named by ${namedBy})`);
      continue;
    }
    const stat = fs.statSync(absolutePath);
    if (stat.isFile() && stat.size === 0) {
      problems.push(`empty ${relativePath} (named by ${namedBy})`);
    }
  }

  // A per-ABI archive directory carries the archives the manifests name and
  // nothing else: a stray library from an earlier build would ship a second,
  // unused payload and inflate the download.
  const archiveDirectories = new Set(
    [...requirements.keys()]
      .filter((relativePath) => relativePath.startsWith("android/src/main/jniLibs/"))
      .map((relativePath) => path.posix.dirname(relativePath)),
  );
  for (const directory of archiveDirectories) {
    const absoluteDirectory = path.join(packageDirectory, directory);
    if (!fs.existsSync(absoluteDirectory)) {
      continue;
    }
    for (const member of fs.readdirSync(absoluteDirectory)) {
      const memberPath = path.posix.join(directory, member);
      if (!requirements.has(memberPath)) {
        problems.push(
          `unexpected ${memberPath} (not named by android/CMakeLists.txt; remove it or name it)`,
        );
      }
    }
  }

  // The allow-list must cover every named artifact, or `npm pack` would drop
  // it on a fresh package.
  if (packageJson && Array.isArray(packageJson.files)) {
    for (const [relativePath, namedBy] of requirements) {
      const covered = packageJson.files.some((entry) => {
        const normalized = entry.replace(/^\.\//, "").replace(/\/+$/, "");
        return (
          relativePath === normalized || relativePath.startsWith(`${normalized}/`)
        );
      });
      if (!covered) {
        problems.push(
          `package.json files excludes ${relativePath} (named by ${namedBy})`,
        );
      }
    }
  }

  if (problems.length > 0) {
    for (const problem of problems) {
      console.error(`rn-package-gate: ${problem}`);
    }
    process.exitCode = 1;
  } else {
    console.log(
      `rn-package-gate: ${requirements.size} manifest-named artifacts present`,
    );
  }
} finally {
  fs.rmSync(unpackDirectory, { recursive: true, force: true });
}
