// Tests for scripts/generate-web-facade.mjs.
//
// Run with: node --test scripts/generate-web-facade.test.mjs

import assert from 'node:assert/strict';
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

import {
  GENERATED_RUST_RELATIVE_PATH,
  GENERATED_TYPESCRIPT_RELATIVE_PATH,
  UNIFFI_CONTRACT_RELATIVE_PATH,
  checkWebFacade,
  generateWebFacade,
  main,
} from './generate-web-facade.mjs';

const REPOSITORY_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);

/** Makes a scratch directory the caller must remove. */
function makeScratchDirectory(testContext, prefix) {
  const directory = mkdtempSync(path.join(os.tmpdir(), prefix));
  testContext.after(() => {
    rmSync(directory, { recursive: true, force: true });
  });
  return directory;
}

/** Writes every generated output into a scratch tree. */
function writeGeneratedTree(rootDirectory, generated) {
  for (const [relativePath, content] of generated) {
    const absolutePath = path.join(rootDirectory, relativePath);
    mkdirSync(path.dirname(absolutePath), { recursive: true });
    writeFileSync(absolutePath, content);
  }
}

test('generation is deterministic and carries the generated-file note', () => {
  const first = generateWebFacade();
  const second = generateWebFacade();

  assert.deepEqual([...first.keys()], [
    GENERATED_TYPESCRIPT_RELATIVE_PATH,
    GENERATED_RUST_RELATIVE_PATH,
  ]);
  for (const [relativePath, content] of first) {
    assert.equal(
      content,
      second.get(relativePath),
      `${relativePath} must be stable`,
    );
    assert.ok(content.endsWith('\n'), `${relativePath} must end with a newline`);
    assert.match(
      content,
      /Generated by .*scripts\/generate-web-facade\.mjs/u,
      `${relativePath} must say it is generated`,
    );
    assert.match(
      content,
      /Do not edit this file by hand/u,
      `${relativePath} must warn against hand edits`,
    );
    assert.equal(
      content.includes(REPOSITORY_ROOT),
      false,
      `${relativePath} must not carry a host path`,
    );
  }
  assert.match(
    first.get(GENERATED_TYPESCRIPT_RELATIVE_PATH),
    new RegExp(UNIFFI_CONTRACT_RELATIVE_PATH.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&')),
    'the generated TypeScript must name the UDL as its source',
  );
});

test('the committed façade matches the generator', () => {
  const result = checkWebFacade();
  assert.equal(
    result.isStale,
    false,
    `the committed façade is stale: ${
      result.staleFiles.map((staleFile) => staleFile.relativePath).join(', ')
    }`,
  );
  assert.equal(main(['--check']), 0);
});

test('a one-line drift in the committed TypeScript mirror fails the check', (testContext) => {
  const generated = generateWebFacade();
  const scratchDirectory = makeScratchDirectory(testContext, 'web-facade-drift-');
  writeGeneratedTree(scratchDirectory, generated);

  const typescriptPath = path.join(
    scratchDirectory,
    GENERATED_TYPESCRIPT_RELATIVE_PATH,
  );
  const committedText = readFileSync(typescriptPath, 'utf8');
  const driftedText = committedText.replace(
    '    readonly latitude: number;',
    '    readonly latitude: string;',
  );
  assert.notEqual(driftedText, committedText, 'the drift mutation must apply');
  writeFileSync(typescriptPath, driftedText);

  const result = checkWebFacade({
    rootDirectory: scratchDirectory,
    generated,
  });
  assert.equal(result.isStale, true);
  assert.equal(result.staleFiles.length, 1);
  assert.equal(
    result.staleFiles[0].relativePath,
    GENERATED_TYPESCRIPT_RELATIVE_PATH,
  );
  assert.equal(result.staleFiles[0].reason, 'drifted');
  assert.ok(result.staleFiles[0].difference.firstDifferenceLine > 0);
});

test('a one-line drift in the generated Rust constants fails the check', (testContext) => {
  const generated = generateWebFacade();
  const scratchDirectory = makeScratchDirectory(testContext, 'web-facade-rust-drift-');
  writeGeneratedTree(scratchDirectory, generated);

  const rustPath = path.join(scratchDirectory, GENERATED_RUST_RELATIVE_PATH);
  const committedText = readFileSync(rustPath, 'utf8');
  const driftedText = committedText.replace(
    'pub(crate) const COORDINATE_FIELD_LATITUDE: &str = "latitude";',
    'pub(crate) const COORDINATE_FIELD_LATITUDE: &str = "lat";',
  );
  assert.notEqual(driftedText, committedText, 'the drift mutation must apply');
  writeFileSync(rustPath, driftedText);

  const result = checkWebFacade({
    rootDirectory: scratchDirectory,
    generated,
  });
  assert.equal(result.isStale, true);
  assert.deepEqual(
    result.staleFiles.map((staleFile) => [
      staleFile.relativePath,
      staleFile.reason,
    ]),
    [[GENERATED_RUST_RELATIVE_PATH, 'drifted']],
  );
});

test('a missing generated file fails the check', (testContext) => {
  const generated = generateWebFacade();
  const scratchDirectory = makeScratchDirectory(testContext, 'web-facade-missing-');
  writeGeneratedTree(scratchDirectory, generated);
  rmSync(path.join(scratchDirectory, GENERATED_RUST_RELATIVE_PATH));

  const result = checkWebFacade({
    rootDirectory: scratchDirectory,
    generated,
  });
  assert.equal(result.isStale, true);
  assert.deepEqual(
    result.staleFiles.map((staleFile) => [
      staleFile.relativePath,
      staleFile.reason,
    ]),
    [[GENERATED_RUST_RELATIVE_PATH, 'missing']],
  );
});

test('field names come from the contract', () => {
  const contractPath = path.join(REPOSITORY_ROOT, UNIFFI_CONTRACT_RELATIVE_PATH);
  const contractText = readFileSync(contractPath, 'utf8');
  const renamedContract = contractText.replace(
    '    double width_pixels;',
    '    double width_px;',
  );
  assert.notEqual(renamedContract, contractText, 'the contract mutation must apply');

  const generated = generateWebFacade({ contractText: renamedContract });
  assert.match(
    generated.get(GENERATED_TYPESCRIPT_RELATIVE_PATH),
    /readonly widthPx: number;/u,
    'the TypeScript field name must follow the contract',
  );
});

test('a mapped field removed from the contract fails generation', () => {
  const contractPath = path.join(REPOSITORY_ROOT, UNIFFI_CONTRACT_RELATIVE_PATH);
  const contractText = readFileSync(contractPath, 'utf8');
  const renamedContract = contractText.replace(
    '    double latitude;',
    '    double latitude_degrees;',
  );
  assert.notEqual(renamedContract, contractText, 'the contract mutation must apply');
  assert.throws(
    () => generateWebFacade({ contractText: renamedContract }),
    /COORDINATE_FIELD_LATITUDE/u,
    'the Rust field-name constants must be validated against the contract',
  );
});
