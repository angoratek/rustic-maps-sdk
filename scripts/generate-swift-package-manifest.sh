#!/usr/bin/env bash
# Emit the generated `Package.swift` published on the `swift-package` branch
# (docs/PackagingAndRelease.md §2.2 and §3).
#
# The manifest is the Swift Package Manager consumption path of the
# Releases-only distribution ruling: its `binaryTarget` points at the
# release's XCFramework zip through `url:` and pins it with the archive's
# SHA-256 as the `checksum:` (the same value
# `swift package compute-checksum <zip>` prints). The rest of the package
# (the `Sources/RusticMapsSDK` generated bindings and the `MapNativeCoreUI`
# wrapper) is published on the same branch beside the manifest.
#
# The product, module and package name is `RusticMapsSDK`; the binary target
# keeps the contract-bound generated module name `rustic_mapsFFI`, which
# the generated Swift sources import through `canImport`.
#
# Usage:
#   scripts/generate-swift-package-manifest.sh \
#     --version v0.1.0 \
#     --url https://github.com/angoratek/rustic-maps-sdk/releases/download/v0.1.0/rustic-maps-sdk-ios-v0.1.0.xcframework.zip \
#     --checksum <sha256> \
#     --output /path/to/Package.swift
#
# `--output` defaults to stdout. The output is deterministic: no timestamp,
# host or environment value is written.
set -euo pipefail

readonly SWIFT_TOOLS_VERSION="5.10"
readonly SDK_MODULE_NAME="RusticMapsSDK"
readonly FFI_MODULE_NAME="rustic_mapsFFI"
readonly IOS_MINIMUM_VERSION="17"
readonly SHA256_PATTERN='^[0-9a-f]{64}$'
readonly VERSION_PATTERN='^v?[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z][0-9A-Za-z.-]*)?$'

version=""
archive_url=""
archive_checksum=""
output_path=""

usage() {
    cat >&2 <<'USAGE'
usage: generate-swift-package-manifest.sh --version <vX.Y.Z> --url <https-url>
                                           --checksum <sha256>
                                           [--output <path>]

  --version   release version, used in the generated-file header
  --url       published XCFramework zip URL (https)
  --checksum  archive SHA-256 (`swift package compute-checksum` value)
  --output    output path (default: stdout)
USAGE
}

fail() {
    printf 'error: %s\n' "$1" >&2
    exit 1
}

parse_arguments() {
    while [ "$#" -gt 0 ]; do
        case "$1" in
            --version)
                [ "$#" -ge 2 ] || { usage; exit 2; }
                version="$2"
                shift 2
                ;;
            --url)
                [ "$#" -ge 2 ] || { usage; exit 2; }
                archive_url="$2"
                shift 2
                ;;
            --checksum)
                [ "$#" -ge 2 ] || { usage; exit 2; }
                archive_checksum="$2"
                shift 2
                ;;
            --output)
                [ "$#" -ge 2 ] || { usage; exit 2; }
                output_path="$2"
                shift 2
                ;;
            -h|--help)
                usage
                exit 0
                ;;
            *)
                printf 'error: unknown argument: %s\n' "$1" >&2
                usage
                exit 2
                ;;
        esac
    done
}

validate_arguments() {
    [[ "${version}" =~ ${VERSION_PATTERN} ]] \
        || fail "--version must be a semantic version (vX.Y.Z or X.Y.Z)"
    case "${archive_url}" in
        https://*) ;;
        *) fail "--url must be an https URL" ;;
    esac
    [[ "${archive_checksum}" =~ ${SHA256_PATTERN} ]] \
        || fail "--checksum must be a lowercase 64-character SHA-256 hex digest"
}

emit_manifest() {
    cat <<EOF
// swift-tools-version: ${SWIFT_TOOLS_VERSION}
// Generated by scripts/generate-swift-package-manifest.sh for ${version}.
// Do not edit the \`swift-package\` branch by hand; the release workflow
// rewrites it for every published tag.
//
// Binary target archive: ${archive_url}
// Archive SHA-256 (swift package compute-checksum): ${archive_checksum}
import PackageDescription

/// Apple platforms the XCFramework slices cover; pinned to the oldest
/// release accepted by the Swift 5.10 tools version.
let supportedPlatforms: [SupportedPlatform] = [.iOS(.v${IOS_MINIMUM_VERSION})]

/// Name of the Rust static library module (matches the modulemap inside the
/// XCFramework) and of the binary target importing it. Contract-bound: the
/// generated Swift bindings import it by this name.
let ffiModuleName = "${FFI_MODULE_NAME}"

/// The shipped Swift module/product identity.
let sdkModuleName = "${SDK_MODULE_NAME}"

let package = Package(
    name: sdkModuleName,
    platforms: supportedPlatforms,
    products: [
        .library(name: sdkModuleName, targets: [sdkModuleName]),
        .library(name: "MapNativeCoreUI", targets: ["MapNativeCoreUI"]),
    ],
    targets: [
        .binaryTarget(
            name: ffiModuleName,
            url: "${archive_url}",
            checksum: "${archive_checksum}"
        ),
        .target(
            name: sdkModuleName,
            dependencies: [.target(name: ffiModuleName)],
            path: "Sources/${SDK_MODULE_NAME}",
            // The disk-space required-reason declaration travels with the
            // module whose Rust core reads the free space before it evicts
            // cached tiles.
            resources: [.copy("PrivacyInfo.xcprivacy")]
        ),
        .target(
            name: "MapNativeCoreUI",
            dependencies: [.target(name: sdkModuleName)],
            path: "Sources/MapNativeCoreUI",
            // The shared provider registry, copied flat into the resource
            // bundle (a top-level copied folder named \`Resources\` would yield
            // the macOS bundle layout, which codesign refuses). Demo content
            // stays out of the shipped package: the reference applications
            // bundle \`platform/reference-scenes.json\` from its single source.
            resources: [
                .copy("Resources/providers.json"),
            ]
        ),
    ]
)
EOF
}

main() {
    parse_arguments "$@"
    validate_arguments

    if [ -n "${output_path}" ]; then
        mkdir -p "$(dirname "${output_path}")"
        emit_manifest > "${output_path}"
        printf 'ok: %s\n' "${output_path}" >&2
    else
        emit_manifest
    fi
}

main "$@"
